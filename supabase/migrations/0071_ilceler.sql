alter table public.districts add column if not exists latitude  numeric(9,6);
alter table public.districts add column if not exists longitude numeric(9,6);

/* Kısıtlar `not null` DEĞİL: sütunlar var olan (boş) bir tabloya
   ekleniyor ve ileride resmî bir kaynaktan koordinatsız bir ilçe
   eklenmesi mümkün. Bunun yerine SINIR kontrolü var — Türkiye dışında
   bir koordinat, eşleştirmede sessizce yanlış ilçe seçtirirdi. */
alter table public.districts drop constraint if exists districts_lat_check;
alter table public.districts add constraint districts_lat_check
  check (latitude is null or latitude between 35 and 43);
alter table public.districts drop constraint if exists districts_lon_check;
alter table public.districts add constraint districts_lon_check
  check (longitude is null or longitude between 25 and 45);

